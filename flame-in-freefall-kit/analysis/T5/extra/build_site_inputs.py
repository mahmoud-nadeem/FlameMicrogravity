#!/usr/bin/env python3
"""Derive the website inputs of track T5 from Khaled Adawi's own files (run from the kit root):

    python analysis/T5/extra/build_site_inputs.py

Reads  ../RAG/NASA_ACME_RAG_Corpora_By_Dataset/*/*_RAG_Corpus.txt   (his ACME RAG corpora)
       analysis/T5/PSI-20_bre/README.md, eda/eda_summary.md          (his PSI-20 BRE package)
Writes analysis/T5/extra/test_questions.md   every FAQ chunk (RECORD_KIND faq), question and answer verbatim + chunk ID
       analysis/T5/extra/track_paragraph.md  chunk ACME-01 (Mission scope), verbatim
       analysis/T5/extra/limitations.md      README 'Scientific uncertainty' + EDA 'OUR INFERENCE / limitations', verbatim
       analysis/T5/PSI-*/card.json           'objectives' from each record's objective chunk, only while the card still says TODO
Nothing is paraphrased. Re-run after he updates his corpus or package, then rebuild the site.
"""
import json, re
from pathlib import Path

KIT = Path(__file__).resolve().parents[3]
T5 = KIT / "analysis" / "T5"
CORPORA = KIT.parent / "RAG" / "NASA_ACME_RAG_Corpora_By_Dataset"
OBJECTIVE = {"PSI-10": "PSI10-01", "PSI-20": "PSI20-01", "PSI-22": "PSI22-01", "PSI-23": "PSI23-01"}


def chunks():
    out = {}
    for f in sorted(CORPORA.glob("*/*_RAG_Corpus.txt")):
        for b in re.split(r"\n=+\n", f.read_text(encoding="utf-8")):
            if not b.startswith("CHUNK "):
                continue
            field = lambda k: (re.search(rf"^{k}: (.+)$", b, re.M) or [None, ""])[1].strip()
            out[field("CHUNK \\d+/\\d+ \\| ID") or re.search(r"ID: (\S+)", b).group(1)] = {
                "kind": field("RECORD_KIND"), "investigation": field("INVESTIGATION_ID"), "urls": field("SOURCE_URLS"),
                "content": b.split("CONTENT:", 1)[1].strip(), "file": f.relative_to(KIT.parent).as_posix()}
    return out


def section(path, heading):
    text = path.read_text(encoding="utf-8")
    m = re.search(rf"^##\s*{re.escape(heading)}\s*$(.+?)(?=^##\s|\Z)", text, re.M | re.S)
    return m.group(1).strip() if m else ""


def main():
    c = chunks()
    assert c, f"no corpus found under {CORPORA}"
    faq = [(cid, ch) for cid, ch in c.items() if ch["kind"] == "faq"]
    lines = ["# T5 questions and answers (generated by extra/build_site_inputs.py from Khaled Adawi's ACME RAG corpora; verbatim)", "",
             "## Answerable", ""]
    for i, (cid, ch) in enumerate(faq, 1):
        q = re.search(r"^Question:\s*(.+)$", ch["content"], re.M).group(1).strip()
        a = re.search(r"^Answer:\s*(.+)$", ch["content"], re.M | re.S).group(1).strip().replace("\n", " ")
        lines += [f"{i}. Q: {q}", f"   A: {a} (RAG chunk {cid}, {ch['investigation']})"]
    (T5 / "extra").mkdir(exist_ok=True)
    (T5 / "extra/test_questions.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (T5 / "extra/track_paragraph.md").write_text(
        "# T5 track paragraph: RAG chunk ACME-01 'Mission scope' (Khaled Adawi), verbatim\n\n" + c["ACME-01"]["content"] + "\n", encoding="utf-8")
    pkg = T5 / "PSI-20_bre"
    lim = [section(pkg / "README.md", "Scientific uncertainty"), section(pkg / "eda" / "eda_summary.md", "OUR INFERENCE / limitations")]
    assert all(lim), "limitation sections not found"
    (T5 / "extra/limitations.md").write_text(
        "# T5 limitations: verbatim from PSI-20_bre/README.md ('Scientific uncertainty') and eda/eda_summary.md ('OUR INFERENCE / limitations'), Khaled Adawi\n\n"
        + "\n\n".join(lim) + "\n", encoding="utf-8")
    filled = []
    for psi, cid in OBJECTIVE.items():
        card_path = next(T5.glob(f"{psi}_*/card.json"))
        card = json.loads(card_path.read_text(encoding="utf-8"))
        if not card.get("objectives", "").strip() or "TODO" in card.get("objectives", ""):
            card["objectives"] = c[cid]["content"]
            card["x_objectives_source"] = f"{c[cid]['file']}, chunk {cid} (Khaled Adawi); its sources: {c[cid]['urls']}"
            card_path.write_text(json.dumps(card, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            filled.append(psi)
    print(f"{len(faq)} questions, track paragraph, limitations; objectives filled for {filled or 'none (already set)'}")


if __name__ == "__main__":
    main()
