/* Bondoq (بندق), the crew's cat. He lives on a ledge along the bottom of the screen with a food bowl and a cushion.

   Behaviour: a small state machine with weighted choices and real durations. He walks to the bowl before eating and to the
   cushion before sleeping; eating and sleeping have cooldowns; every state has one timer, so nothing overlaps.
     idle -> wander | look | sit (-> groom) | goEat -> eat | goSleep -> settle -> sleep -> wake -> stretch -> idle
   One instance for the whole visit (built once, never rebuilt on route changes). One interval drives movement and frames;
   it stops while paused, hidden, in a background tab, or with reduced motion (then he naps quietly on his cushion).
   The layer never takes clicks (pointer-events: none). The lane is measured only on resize, never per frame.
   Frames: assets/bondoq/bondoq.png (tools/bondoq_sprites.py). Each animation is a one-time intro (sitting down, settling,
   waking, stretching) and then a loop (breathing, blinks, ear flicks, looking around, chewing...). Walking speed follows the
   legs: one 6-frame gait cycle carries him STRIDE sprite pixels, so his paws never slide.
   Controls: the cat icon in the top bar opens Show Bondoq / Bondoq moving (controls.js). */
(function () {
  const F = window.FIF;
  if (!F || F.bondoq) return;
  const FW = 52, FH = 42;
  // generated by tools/bondoq_sprites.py (assets/bondoq/bondoq.json "anims"): cell indexes, intro once then loop
  const ANIMS = {"walk":{"intro":[],"loop":[0,1,2,3,4,5]},"stand":{"intro":[],"loop":[6,6,7,7,6,6,7,8,7,6,9,6]},"look":{"intro":[],"loop":[6,10,10,6,11,12,11,6]},"sit":{"intro":[13],"loop":[14,15,14,15,18,18,14,16,15,17,14,19,19,15]},"groom":{"intro":[],"loop":[20,21,20,21,20,21,22,22,23,14]},"eat":{"intro":[6,24],"loop":[25,26,25,26,25,24]},"settle":{"intro":[13,14,27],"loop":[28,29]},"loaf":{"intro":[],"loop":[28,28,29,29]},"sleep":{"intro":[],"loop":[32,32,33,33,32,32,33,33,34,32,33,33]},"wake":{"intro":[35,30,31,30],"loop":[28]},"stretch":{"intro":[27,36,37,38,37,36],"loop":[6]}};
  const FRAME_MS = { walk: 120, stand: 420, look: 520, sit: 600, groom: 420, eat: 380, settle: 900, loaf: 1100, sleep: 900, wake: 400, stretch: 330 };
  const INTRO_MS = { sit: 260, eat: 220, settle: 380, wake: 400, stretch: 330 };
  const STRIDE = 16, WALK_CYCLE_MS = FRAME_MS.walk * ANIMS.walk.loop.length;
  const rnd = (a, b) => a + Math.random() * (b - a);
  const reduced = () => !!F.settings.reduceMotion || (window.matchMedia && matchMedia("(prefers-reduced-motion: reduce)").matches);
  if (F.settings.bondoq === undefined) F.settings.bondoq = true;
  if (F.settings.bondoqPaused === undefined) F.settings.bondoqPaused = false;
  try { const v = JSON.parse(localStorage.getItem("fif.bondoq")); if (typeof v === "boolean") F.settings.bondoq = v; } catch (e) {}
  try { const v = JSON.parse(localStorage.getItem("fif.bondoqPaused")); if (typeof v === "boolean") F.settings.bondoqPaused = v; } catch (e) {}

  let hab, cat, bowl, bed, scale = 2, laneL = 0, laneR = 600, timer = null, built = false, blocked = false;
  const s = { name: "idle", until: 0, x: 120, dir: 1, target: null, then: null, frame: 0, frameAt: 0, lastEat: -Infinity, lastSleep: -Infinity, log: [] };
  const catW = () => FW * scale;
  const bowlX = () => laneL + catW() * 0.8;                     // bowl near the left end, with room for him beside it
  const bedX = () => laneR - 64 * scale;                        // cushion near the right end
  // eating: his head (about 73% across the frame, facing right) over the middle of the bowl
  const spot = { eat: () => bowlX() + 10 * scale - catW() * 0.73, sleep: () => bedX() + 4 * scale };

  function build() {
    hab = document.createElement("div"); hab.id = "bondoq-habitat"; hab.setAttribute("aria-hidden", "true");
    hab.innerHTML = `<div class="bq-ledge"></div><img class="bq-bowl" src="assets/bondoq/bowl.png" alt=""><img class="bq-bed" src="assets/bondoq/bed.png" alt=""><div class="bq-cat"></div>`;
    document.body.appendChild(hab);
    cat = hab.querySelector(".bq-cat"); bowl = hab.querySelector(".bq-bowl"); bed = hab.querySelector(".bq-bed");
    built = true;
  }

  function measure() {                                           // only on resize/rotation, route or panel changes
    scale = window.innerWidth < 720 ? 1.25 : 2;
    hab.style.setProperty("--bq", scale);
    const launch = document.getElementById("chat-launch");
    const right = launch && launch.getClientRects().length ? launch.getBoundingClientRect().left - 12 : window.innerWidth - 16;
    // start after the HUD telemetry line when it sits in the ledge band (cinematic view)
    const tel = document.getElementById("hud-telemetry"), tr = tel && tel.getClientRects().length ? tel.getBoundingClientRect() : null;
    laneL = tr && tr.bottom > window.innerHeight - FH * scale - 8 && tr.right < window.innerWidth / 2 ? Math.round(tr.right + 16) : 12;
    laneR = Math.max(laneL + catW() * 2, right);                // phones: a compact ledge that ends before "Ask the crew"
    bowl.style.left = bowlX() + "px"; bed.style.left = bedX() + "px";
    s.x = Math.min(Math.max(s.x, laneL), laneR - catW());        // stay inside the ledge after a resize
    if (s.target != null) s.target = Math.min(Math.max(s.target, laneL), laneR - catW());
    draw(true);
  }

  let lastIdx = -1, lastT = "";
  function draw(force) {
    const a = ANIMS[s.anim] || ANIMS.stand, n = a.intro.length;
    const idx = s.frame < n ? a.intro[s.frame] : a.loop[(s.frame - n) % a.loop.length];
    const t = `translate3d(${Math.round(s.x)}px,0,0) scaleX(${s.dir < 0 ? -1 : 1})`;
    if (force || idx !== lastIdx) { cat.style.backgroundPosition = `${-idx * FW * scale}px 0`; lastIdx = idx; }
    if (force || t !== lastT) { cat.style.transform = t; lastT = t; }
  }

  function enter(name, ms, anim, then) {
    s.name = name; s.anim = anim || name; s.frame = 0; s.frameAt = performance.now(); s.until = ms ? performance.now() + ms : 0; s.then = then || null;
    s.log.push(name); if (s.log.length > 40) s.log.shift();
    hab.dataset.state = name;
    draw(true);
  }

  function walkTo(x, then) {
    const t = Math.min(Math.max(x, laneL), laneR - catW());
    if (Math.abs(t - s.x) < 4) { then(); return; }
    s.target = t; s.dir = t > s.x ? 1 : -1;                     // he faces where he is going
    s.lastTick = performance.now();
    enter("walk", 0, "walk", then);
  }

  function choose() {                                            // weighted next step from idle
    const now = performance.now(), wide = laneR - laneL > catW() * 3;
    const opts = [["wander", 34], ["look", 18], ["sit", 20], ["idle", 6]];
    if (wide && now - s.lastEat > 90000) opts.push(["eat", 12]);
    if (wide && now - s.lastSleep > 150000) opts.push(["sleep", 10]);
    let r = Math.random() * opts.reduce((a, o) => a + o[1], 0);
    const pick = opts.find((o) => (r -= o[1]) < 0)[0];
    if (pick === "wander") {
      let x, n = 0; do { x = rnd(laneL, laneR - catW()); } while (Math.abs(x - s.x) < 60 && ++n < 6);
      walkTo(x, () => enter("pause", rnd(900, 1800), "stand", idle));
    } else if (pick === "look") enter("look", rnd(2400, 4200));
    else if (pick === "sit") enter("sit", rnd(3000, 6000), "sit", () => (Math.random() < 0.55 ? enter("groom", rnd(2800, 4800), "groom", () => enter("sit", rnd(1200, 2400), "sit", idle)) : idle()));
    else if (pick === "eat") walkTo(spot.eat(), () => { s.dir = 1; enter("eat", rnd(4500, 7500), "eat", () => { s.lastEat = performance.now(); idle(); }); });
    else if (pick === "sleep") walkTo(spot.sleep(), () => enter("settle", rnd(2400, 3200), "settle", () => enter("sleep", rnd(15000, 30000), "sleep",
      () => enter("wake", 1700, "wake", () => enter("stretch", 2100, "stretch", () => { s.lastSleep = performance.now(); idle(); })))));
    else idle();
  }
  function idle() { s.target = null; enter("idle", rnd(1500, 3500), "stand", choose); }

  function tick() {
    const now = performance.now();
    const a = ANIMS[s.anim] || ANIMS.stand;
    const fm = s.frame < a.intro.length ? (INTRO_MS[s.anim] || 260) : FRAME_MS[s.anim] || 500;
    if (now - s.frameAt >= fm) { s.frame++; s.frameAt = now; }
    const dt = Math.min(200, now - (s.lastTick || now)); s.lastTick = now;
    if (s.name === "walk" && s.target != null) {
      const step = scale * STRIDE * dt / WALK_CYCLE_MS;         // speed matched to the gait: one stride per cycle
      if (Math.abs(s.target - s.x) <= step) { s.x = s.target; s.target = null; const t = s.then; s.then = null; if (t) t(); else idle(); }
      else s.x += step * s.dir;
    } else if (s.until && now >= s.until) { const t = s.then; s.then = null; s.until = 0; if (t) t(); else idle(); }
    draw();
  }

  function running() { return F.settings.bondoq && !F.settings.bondoqPaused && !document.hidden && !blocked && !reduced(); }
  function sync() {                                              // start or stop the single loop; static nap with reduced motion
    if (!built) return;
    hab.hidden = !F.settings.bondoq;
    hab.classList.toggle("is-tucked", blocked);
    document.body.classList.toggle("has-bondoq", !!F.settings.bondoq);
    const want = running();
    if (want && !timer) { timer = setInterval(tick, 90); if (!s.until && s.name !== "walk") idle(); }
    if (!want && timer) { clearInterval(timer); timer = null; }
    if (F.settings.bondoq && reduced() && !timer) { s.x = spot.sleep(); s.dir = 1; s.anim = "loaf"; s.frame = 0; hab.dataset.state = "rest"; draw(true); }
  }

  // panels he must not sit in front of: the open crew panel, the document viewer
  function updateBlocked() {
    const chat = document.getElementById("chat");
    blocked = !!(chat && !chat.hidden) || /^#\/shorts/.test(location.hash);
    sync();
  }

  function init() {
    if (built) return;
    build(); measure();                                     // his show/pause switches are in the cat menu (controls.js)
    s.x = rnd(laneL + 40, Math.max(laneL + 41, laneR - catW() - 40));
    let rt = null;
    window.addEventListener("resize", () => { clearTimeout(rt); rt = setTimeout(measure, 150); });
    window.addEventListener("orientationchange", () => setTimeout(measure, 200));
    document.addEventListener("visibilitychange", sync);
    window.addEventListener("hashchange", () => { updateBlocked(); measure(); });
    document.addEventListener("fif:settings", (e) => { const k = e.detail && e.detail.key;
      if (k === "reduceMotion" || k === "bondoq" || k === "bondoqPaused") sync(); if (k === "cinematic") setTimeout(measure, 50); });
    if (window.matchMedia) matchMedia("(prefers-reduced-motion: reduce)").addEventListener?.("change", sync);
    const chat = document.getElementById("chat");
    if (chat) new MutationObserver(updateBlocked).observe(chat, { attributes: true, attributeFilter: ["hidden"] });
    updateBlocked();
  }

  F.bondoq = {
    get state() { return s.name; }, get anim() { return s.anim; }, get x() { return s.x; }, get running() { return !!timer; },
    get lane() { return [laneL, laneR]; }, get history() { return s.log.slice(); }, get spots() { return { bowl: spot.eat(), bed: spot.sleep() }; },
    // for tests and demos: start a behaviour now (eat and sleep still walk to the bowl / cushion first)
    act(name) { if (!timer) return false; s.until = 0; s.then = null; s.target = null;
      ({ wander: () => walkTo(laneL + (laneR - laneL) / 2, idle), look: () => enter("look", 3000), sit: () => enter("sit", 2500, "sit", idle),
         groom: () => enter("sit", 600, "sit", () => enter("groom", 3500, "groom", idle)),
         eat: () => walkTo(spot.eat(), () => { s.dir = 1; enter("eat", 4500, "eat", () => { s.lastEat = performance.now(); idle(); }); }),
         sleep: () => walkTo(spot.sleep(), () => enter("settle", 2400, "settle", () => enter("sleep", 4000, "sleep", () => enter("wake", 1700, "wake", () => enter("stretch", 2100, "stretch", () => { s.lastSleep = performance.now(); idle(); }))))) }[name] || idle)();
      return true; },
    place(x) { s.x = Math.min(Math.max(x, laneL), laneR - catW()); draw(true); },   // tests: put him somewhere on the ledge
    sync, measure, init,
  };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init); else init();
})();
